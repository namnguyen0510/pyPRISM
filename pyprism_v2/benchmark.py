"""
pyprism_v2.benchmark
====================
The sweep driver.

For each instance ``(n, k, seed)`` with ``depth = k * n``, it builds the light
cone and both hypergraph tracks, runs every available method, and scores all of
them on the **exact Track 2 cost** --- because that is what a distributed
compiler actually pays, whatever substrate the method was given to optimise on.

Single-objective methods contribute their partition's own CD/CK mode front;
multi-objective methods contribute the front they return.  Front quality is
compared by hypervolume against a common reference point per instance, so the
numbers are comparable across methods but not across instances.

Two PRISM variants are run, both on the Track 2 substrate:

    PRISM    light cone + symmetry + irreducibility hypergraph, with the
             two-dimensional (w, T) replica ladder, every replica seeded at
             random
    PRISM+   the same, multi-started from the official METIS and KaHyPar
             solutions
"""
from __future__ import annotations

import time
import traceback
from dataclasses import asdict

import numpy as np

from .circuits import random_circuit, circuit_stats
from .lightcone import light_cone_graph, lightcone_stats
from .hypergraph import build_track1, build_track2, extract_packets
from .objectives import (CostState, mode_front, evaluate, knee, balance,
                         hypervolume, igd, pareto, objective_correlation)
from .partition import available, REGISTRY, PrismConfig, part_prism
from .partition.baselines import part_naive

__all__ = ['run_instance', 'sweep', 'DEFAULT_NS', 'DEFAULT_KS']

DEFAULT_NS = (20, 50, 100, 200)
DEFAULT_KS = (2, 3, 4)


def rescore_front(front, hg2):
    """Re-express a front in the exact Track 2 currency.

    A method given H1 returns a front measured in H1's worst-case units, which
    is not comparable to anything else.  Every method is *scored* on what a
    distributed compiler actually pays, so the masks are kept and their mode
    fronts rebuilt on H2.
    """
    out, seen = [], set()
    for p in front:
        m = p[2]
        if m in seen:
            continue
        seen.add(m)
        st = CostState(hg2, m)
        for E, K in mode_front(st.costs()):
            out.append((E, K, m))
    return pareto(out)


def default_moo_budget(n):
    """Population-based search costs one full evaluation per offspring, which
    is ``O(|nets|)``; the budget therefore has to shrink as the instance grows
    or the evolutionary methods dominate the sweep.  Reported in the results so
    the comparison stays honest about who was given what."""
    if n <= 32:
        return dict(pop_size=40, generations=30, points=15, restarts=3)
    if n <= 64:
        return dict(pop_size=32, generations=20, points=12, restarts=2)
    if n <= 128:
        return dict(pop_size=24, generations=12, points=8, restarts=1)
    return dict(pop_size=16, generations=8, points=6, restarts=1)


def _front_metrics(front, ref):
    if not front:
        return dict(front_size=0, hv=0.0, min_E=np.nan, min_K=np.nan)
    E = [p[0] for p in front]
    K = [p[1] for p in front]
    return dict(front_size=len(front), hv=hypervolume(front, ref),
                min_E=float(min(E)), min_K=float(min(K)))


def run_instance(n, depth, seed, family='rqc', topology='grid', eps=0.10,
                 cfg: PrismConfig | None = None, skip=(), kahypar_ini=None,
                 moo_budget=None, verbose=False, circuit=None, hgs=None):
    """Partition one circuit by every available method.

    Returns ``(rows, meta, fronts, circuit)`` where ``circuit`` is the
    ``(layout, gates)`` actually benchmarked.  It is handed back rather than
    regenerated by the caller: re-deriving it from the same arguments happens
    to give the same circuit today, but that is an invariant nobody would
    notice breaking, and a saved circuit that differs from the benchmarked one
    is worse than no saved circuit at all.

    ``circuit`` and ``hgs`` let a caller supply a circuit and its substrates
    instead of generating them, which is how a stored instance is benchmarked:
    the same reasoning that makes the circuit an output makes re-deriving a
    *saved* one from its recorded arguments the wrong move.  ``n``, ``depth``,
    ``seed`` and the two family labels then serve only to name the rows.
    """
    from .partition.prism import scaled_sweeps
    cfg = cfg or PrismConfig(eps=eps, seed=seed, workers=1,
                             sweeps=scaled_sweeps(n))
    t0 = time.time()

    if circuit is None:
        layout, gates, adj = random_circuit(n, depth, seed=seed, family=family,
                                            topology=topology)
    else:
        layout, gates = circuit[0], circuit[1]
    lc, lc_first, lc_full = light_cone_graph(n, layout)
    lcs = lightcone_stats(lc, lc_first, lc_full, n, depth)
    hg1, hg2 = hgs if hgs is not None else (build_track1(n, gates),
                                            build_track2(n, gates))
    packets, covered = extract_packets(n, gates)
    s1, s2 = hg1.stats(), hg2.stats()

    # a common reference point per instance: the trivial partition's currencies
    base = CostState(hg2, part_naive(n))
    ref = (max(base.E, 1.0) * 1.05, max(base.K, 1e-9) * 1.05)

    rows, fronts, single_masks = [], {}, {}
    moo_kw = moo_budget if moo_budget is not None else default_moo_budget(n)

    def score(label, front, dt, note=''):
        front = rescore_front(front, hg2)
        fm = _front_metrics(front, ref)
        kn = knee(front) if front else (np.nan, np.nan, 0)
        mask = kn[2] if front and len(kn) > 2 else 0
        E, K = (evaluate(hg2, mask) if mask else (np.nan, np.nan))
        rows.append({'n': n, 'depth': depth, 'k': depth // n, 'seed': seed,
                     'family': family, 'topology': topology, 'method': label,
                     'E_CD': E, 'K_CK': K, 'knee_E': kn[0], 'knee_K': kn[1],
                     'balance': balance(mask, n) if mask else np.nan,
                     'seconds': dt, 'note': note, **fm})
        fronts[label] = front

    for m in available(n, extra_skip=skip):
        hgs = ([('H1', hg1), ('H2', hg2)] if m.track == 'both'
               else [(m.track, hg1 if m.track == 'H1' else hg2)])
        for tag, hg in hgs:
            label = f'{m.name}/{tag}' if m.track == 'both' else m.name
            t = time.time()
            try:
                kw = dict(seed=seed, eps=eps, lc=lc)
                if m.needs == 'kahypar':
                    kw['ini'] = kahypar_ini
                if m.kind == 'multi':
                    kw.pop('lc', None)
                    kw.update({k: v for k, v in moo_kw.items()
                               if k in m.fn.__code__.co_varnames
                               or m.name.startswith('pymoo')})
                    front = m.fn(n, hg, **kw)
                else:
                    mask = m.fn(n, hg, **kw)
                    single_masks[label] = mask
                    st = CostState(hg2, mask)
                    front = pareto([(E, K, mask)
                                    for E, K in mode_front(st.costs())])
                score(label, front, time.time() - t, m.note)
            except Exception as exc:                        # pragma: no cover
                if verbose:
                    traceback.print_exc()
                rows.append({'n': n, 'depth': depth, 'k': depth // n,
                             'seed': seed, 'family': family,
                             'topology': topology, 'method': label,
                             'E_CD': np.nan, 'K_CK': np.nan,
                             'seconds': time.time() - t,
                             'note': f'FAILED: {type(exc).__name__}: {exc}',
                             'front_size': 0, 'hv': 0.0,
                             'min_E': np.nan, 'min_K': np.nan,
                             'knee_E': np.nan, 'knee_K': np.nan,
                             'balance': np.nan})

    # ---- PRISM and PRISM+ -------------------------------------------------
    # Both run on H2: the light-cone-augmented, symmetry- and
    # irreducibility-aware hypergraph *is* what PRISM means.  They differ only
    # in seeding -- PRISM starts every replica at random, PRISM+ multi-starts
    # from the official METIS and KaHyPar solutions.
    prism_seeds = [single_masks[k] for k in
                   ('METIS/H2', 'KaHyPar/H2', 'METIS/H1', 'KaHyPar/H1')
                   if k in single_masks]
    seed_note = 'METIS + KaHyPar'
    if not prism_seeds:
        # neither external partitioner installed: fall back to the best
        # structural solutions available so PRISM+ still means something
        prism_seeds = [single_masks[k] for k in ('KL/H2', 'Spectral/H2',
                                                 'Greedy/H2', 'KL/H1')
                       if k in single_masks]
        seed_note = 'KL + Spectral (METIS/KaHyPar not installed)'

    t = time.time()
    fr, dg = part_prism(n, hg2, cfg, seeds=None, lc=lc, label='PRISM')
    score('PRISM', fr, time.time() - t,
          f"random seeding; swapT={dg['swap_accept_T']:.2f} "
          f"swapW={dg['swap_accept_w']:.2f}")

    t = time.time()
    frp, dgp = part_prism(n, hg2, cfg, seeds=prism_seeds or None, lc=lc,
                          label='PRISM+')
    score('PRISM+', frp, time.time() - t,
          f"multi-start from {seed_note} ({dgp['seeded']} seeds)")

    # per-instance front-quality normalisation and a reference front
    ref_front = pareto([p for f in fronts.values() for p in f])
    best_hv = max((r['hv'] for r in rows), default=1.0) or 1.0
    for r in rows:
        r['hv_norm'] = r['hv'] / best_hv
        r['igd'] = igd(fronts.get(r['method'], []), ref_front)

    rho1, _ = objective_correlation(hg1, n, samples=200, eps=eps, seed=seed)
    rho2, ns = objective_correlation(hg2, n, samples=200, eps=eps, seed=seed)
    meta = {'n': n, 'depth': depth, 'k': depth // n, 'seed': seed,
            **circuit_stats(gates, n, depth),
            'H1_nets': s1['nets'], 'H2_nets': s2['nets'],
            'H1_pins': s1['pins'], 'H2_pins': s2['pins'],
            'packets': s2['packets'], 'packed_gates': len(covered),
            'compression': s1['nets'] / max(s2['nets'], 1),
            'spearman_H1': rho1, 'spearman_H2': rho2,
            'ref_front_size': len(ref_front),
            'wall': time.time() - t0}
    meta.update({f'lc_{k}': v for k, v in lcs.items()})
    return rows, meta, fronts, (layout, gates)


def sweep(ns=DEFAULT_NS, ks=DEFAULT_KS, seeds=(0,), family='rqc',
          topology='grid', eps=0.10, cfg=None, skip=(), kahypar_ini=None,
          moo_budget=None, progress=True, verbose=False, keep_fronts=2,
          save_dir=None, save_qasm=True):
    """Full sweep: ``depth = k * n`` for every ``(n, k, seed)``.

    ``keep_fronts`` retains the CD/CK fronts of the first few instances so the
    study can draw them; fronts are large, so they are not kept for all.

    ``save_dir`` writes every circuit instance there -- lossless JSON plus
    OpenQASM -- so a study can be reproduced or the circuits reused without
    re-running the generator.
    """
    rows, metas, kept, saved = [], [], {}, []
    jobs = [(n, k, s) for n in ns for k in ks for s in seeds]
    t0 = time.time()
    for i, (n, k, s) in enumerate(jobs, 1):
        depth = k * n
        r, m, fr, (lay, gts) = run_instance(
            n, depth, s, family=family, topology=topology, eps=eps, cfg=cfg,
            skip=skip, kahypar_ini=kahypar_ini, moo_budget=moo_budget,
            verbose=verbose)
        rows += r
        metas.append(m)
        if save_dir:
            from .io import save_instance
            saved.append(save_instance(
                save_dir, f'n{n}_k{k}_s{s}', lay, gts, n,
                meta={'n_qubits': n, 'depth': depth, 'k': k, 'seed': s,
                      'family': family, 'topology': topology,
                      'generator': 'pyprism_v2.circuits.random_circuit',
                      'relabel': True},
                qasm=save_qasm))
        if len(kept) < keep_fronts:
            kept[f'n{n}_k{k}_s{s}'] = {lab: [(p[0], p[1]) for p in f]
                                       for lab, f in fr.items()}
        if progress:
            print(f'  [{i}/{len(jobs)}] n={n:4d} k={k} D={depth:4d} '
                  f'gates={m["gates"]:7d} H1={m["H1_nets"]:6d} '
                  f'H2={m["H2_nets"]:6d} ({m["compression"]:.2f}x) '
                  f'{m["wall"]:7.1f}s  [{time.time()-t0:7.1f}s total]',
                  flush=True)
    return rows, metas, kept, saved
